/* eslint-disable no-console -- A command-line script: it reports to the terminal and runs builds and browser steps one at a time. */
// Generates `src/tokens.stylex.ts` from the public `vars` contract of the built Vanilla Extract
// package. StyleX only accepts static values in `.stylex.ts` files and cannot import the contract
// tree from a plain module, so the token names reach StyleX through this generated mirror. The
// values stay `var(--luke-*)` references: theme stylesheets remain the only source of values.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const themeModule = new URL('../../../../packages/@luke-ui/react/dist/theme.js', import.meta.url);
const { vars } = await import(themeModule.href);

const typeStyles = Object.keys(vars.font).filter((key) => {
	return typeof vars.font[key] === 'object' && 'fontSize' in vars.font[key];
});

const header = `// Generated by scripts/generate-tokens.mjs from @luke-ui/react/theme. Do not edit.
import * as stylex from '@stylexjs/stylex';
`;

const body = `
/** The public token contract as StyleX constants. Each leaf inlines its \`var(--luke-*)\` reference. */
export const vars = stylex.unstable_defineConstsNested(${JSON.stringify(vars, null, '\t')});

/** Private Capsize trims the theme stylesheet writes per type style. */
export const trims = stylex.unstable_defineConstsNested(${JSON.stringify(
	Object.fromEntries(
		typeStyles.map((style) => [
			style,
			{
				baseline: `var(--luke-internal-font-${style}-baseline-trim)`,
				capHeight: `var(--luke-internal-font-${style}-cap-height-trim)`,
			},
		]),
	),
	null,
	'\t',
)});
`;

const target = fileURLToPath(new URL('../src/tokens.stylex.ts', import.meta.url));
writeFileSync(target, header + body);
console.log(`Wrote ${target} (${typeStyles.length} type styles)`);
