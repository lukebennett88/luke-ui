/**
 * Writes the final CSS text from a theme's resolved identity and per-mode values. This is the
 * pipeline's last step, and it does no colour or contrast work: it formats contract pairs and the
 * values already resolved for them into the emitted stylesheet's rule blocks.
 */

import { precomputeValues } from '@capsizecss/vanilla-extract';
import {
	flattenThemeContract,
	partitionContractPairs,
	spaceScale,
	typeStyles,
	typeStyleWeightRole,
} from './contract.js';
import type { IdentityPath, ModePath, SpaceStep, TypeStyle } from './contract.js';
import type { ThemeFoundation } from './foundation.js';
import {
	codeFontFamilyStack,
	defaultFontFamily,
	defaultFontWeights,
	defaultRadius,
	themeFontFamilyStacks,
} from './foundation.js';
import { pathEntry, pathRecord } from './path-record.js';
import { getThemeClassName } from './theme-class-name.js';
import {
	CONTROL_SIZE_VALUES,
	FONT_METRICS,
	FONT_VALUES,
	ICON_SIZE_VALUES,
	INTERACTION_VALUES,
	MOTION_VALUES,
} from './token-values.js';

type ColorMode = 'light' | 'dark';

/**
 * Emits the five rule blocks: an identity rule, the base light rule, the
 * `prefers-color-scheme: dark` media rule, and the two explicit `data-color-mode` rules. The
 * identity rule carries every non-mode contract leaf. Throws when a contract leaf has no resolved
 * value.
 */
export function assembleStylesheet(
	foundation: ThemeFoundation,
	lightValues: Record<ModePath, string>,
	darkValues: Record<ModePath, string>,
): string {
	const selector = `.${getThemeClassName(foundation.name)}`;
	const { identityPairs, modePairs } = partitionContractPairs(flattenThemeContract());

	const identityDeclarations = declarations(identityPairs, buildIdentityValues(foundation));
	const lightDeclarations = ['color-scheme: light;', ...declarations(modePairs, lightValues)];
	const darkDeclarations = ['color-scheme: dark;', ...declarations(modePairs, darkValues)];

	// Every rule pairs a `:where(:root)` fallback with the identity class, so one stylesheet themes
	// the whole document, including body-level portals. `:where()` zeroes the fallback's specificity
	// to (0,0,0), so an explicit identity always outranks another loaded theme's fallback, whatever
	// the stylesheet order. The explicit attribute rules are (0,2,0), so they beat the (0,1,0)
	// media-query rule wherever the attribute sits, whether on the theme root, inside its subtree,
	// or on an ancestor. Every scope sets native color-scheme, and the output is unlayered on purpose.
	const rootAndIdentitySelector = [':where(:root),', `${selector} {`];
	const attributeSelectors = (attributeMode: ColorMode) => {
		return [
			`:where(:root[data-color-mode='${attributeMode}']),`,
			`:where(:root) :where([data-color-mode='${attributeMode}']),`,
			`${selector}[data-color-mode='${attributeMode}'],`,
			`${selector} [data-color-mode='${attributeMode}'],`,
			`[data-color-mode='${attributeMode}'] ${selector} {`,
		].join('\n');
	};

	return [
		'/* Generated by buildTheme from @luke-ui/react. Do not edit. */',
		...rootAndIdentitySelector,
		...identityDeclarations.map(indent),
		'}',
		'',
		...rootAndIdentitySelector,
		...lightDeclarations.map(indent),
		'}',
		'',
		'@media (prefers-color-scheme: dark) {',
		...rootAndIdentitySelector.map(indent),
		...darkDeclarations.map(indent).map(indent),
		indent('}'),
		'}',
		'',
		attributeSelectors('light'),
		...lightDeclarations.map(indent),
		'}',
		'',
		attributeSelectors('dark'),
		...darkDeclarations.map(indent),
		'}',
		'',
	].join('\n');
}

function buildIdentityValues(foundation: ThemeFoundation): { [Path in IdentityPath]: string } {
	const fontFamily = foundation.typography?.fontFamily ?? defaultFontFamily;
	const fontWeight = foundation.typography?.fontWeight;
	const radius = foundation.radius;
	const resolvedWeights = {
		body: String(fontWeight?.body ?? defaultFontWeights.body),
		emphasis: String(fontWeight?.emphasis ?? defaultFontWeights.emphasis),
		heading: String(fontWeight?.heading ?? defaultFontWeights.heading),
		label: String(fontWeight?.label ?? defaultFontWeights.label),
	};
	const bodyFontFamily = themeFontFamilyStacks[fontFamily];
	return {
		...CONTROL_SIZE_VALUES,
		...INTERACTION_VALUES,
		...FONT_VALUES,
		...buildCapsizeValues(fontFamily),
		...typeStyleValues('fontFamily', () => bodyFontFamily),
		...typeStyleValues('fontWeight', (style) => resolvedWeights[typeStyleWeightRole[style]]),
		'font.family.body': bodyFontFamily,
		'font.family.code': codeFontFamilyStack,
		'font.weight.body': resolvedWeights.body,
		'font.weight.emphasis': resolvedWeights.emphasis,
		'font.weight.heading': resolvedWeights.heading,
		'font.weight.label': resolvedWeights.label,
		'radius.control': `${radius?.control ?? defaultRadius.control}px`,
		'radius.detail': `${radius?.detail ?? defaultRadius.detail}px`,
		'radius.full': '9999px',
		'radius.overlay': `${radius?.overlay ?? defaultRadius.overlay}px`,
		'radius.surface': `${radius?.surface ?? defaultRadius.surface}px`,
		...spaceValues(),
		...ICON_SIZE_VALUES,
		...MOTION_VALUES,
	};
}

function typeStyleValues<Field extends string>(
	field: Field,
	valueFor: (style: TypeStyle) => string,
): { [P in `font.${TypeStyle}.${Field}`]: string } {
	return pathRecord(
		typeStyles.map((style) => pathEntry(`font.${style}.${field}`, valueFor(style))),
	);
}

function spaceValues(): { [Step in SpaceStep as `space.${Step}`]: string } {
	return pathRecord(spaceScale.map(([step, value]) => pathEntry(`space.${step}`, value)));
}

function buildCapsizeValues(fontFamily: keyof typeof FONT_METRICS): {
	[Style in TypeStyle as `font.${Style}.baselineTrim`]: string;
} & {
	[Style in TypeStyle as `font.${Style}.capHeightTrim`]: string;
} {
	return pathRecord(
		typeStyles.flatMap((style) => {
			const { baselineTrim, capHeightTrim } = capsizeTrims(fontFamily, style);
			return [
				pathEntry(`font.${style}.baselineTrim`, baselineTrim),
				pathEntry(`font.${style}.capHeightTrim`, capHeightTrim),
			];
		}),
	);
}

function capsizeTrims(fontFamily: keyof typeof FONT_METRICS, style: TypeStyle) {
	const fontSize = Number.parseFloat(FONT_VALUES[`font.${style}.fontSize`]);
	const leading = Number.parseFloat(FONT_VALUES[`font.${style}.lineHeight`]);
	return precomputeValues({
		fontMetrics: FONT_METRICS[fontFamily],
		fontSize,
		leading,
	});
}

function declarations<Path extends string>(
	pairs: Array<[Path, string]>,
	values: Record<Path, string>,
): Array<string> {
	return pairs.map(([path, varName]) => {
		const value = values[path];
		if (value === undefined) throw new Error(`buildTheme did not generate a value for "${path}"`);
		return `${varName}: ${value};`;
	});
}

function indent(line: string): string {
	return `\t${line}`;
}
