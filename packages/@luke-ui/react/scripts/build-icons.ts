#!/usr/bin/env tsx

import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'node-html-parser';

const WHITESPACE_RUN_PATTERN = /\s+/g;
const TAG_GAP_PATTERN = />\s+</g;
const SPACE_BEFORE_TAG_END_PATTERN = /\s+(\/?>)/g;
const UNSAFE_URL_CHARACTER_PATTERN = /[%#<>{}\\]/g;
const INPUT_DIR = path.resolve(process.cwd(), 'icons');
// See `vite.config.ts`'s `copy` config for why this writes to `.generated/` instead of `dist/`.
const GENERATED_DIR = path.resolve(process.cwd(), '.generated');
const ICON_DATA_TS_PATH = path.resolve(GENERATED_DIR, 'icon-data.ts');
const ICON_MASK_DATA_TS_PATH = path.resolve(GENERATED_DIR, 'icon-mask-data.ts');

/**
 * Encodes SVG source for a double-quoted `data:` URL with as little escaping as browsers accept:
 * whitespace collapses, attribute quotes become single quotes, and only the characters that would
 * end the URL or start an escape or fragment are percent-encoded. Full `encodeURIComponent` output
 * is roughly half again as large.
 */
function toDataUriPayload(svg: string): string {
	return svg
		.trim()
		.replaceAll(WHITESPACE_RUN_PATTERN, ' ')
		.replaceAll(TAG_GAP_PATTERN, '><')
		.replaceAll(SPACE_BEFORE_TAG_END_PATTERN, '$1')
		.replaceAll('"', "'")
		.replaceAll(UNSAFE_URL_CHARACTER_PATTERN, (character) => encodeURIComponent(character));
}

async function writeIfChanged(filepath: string, content: string): Promise<boolean> {
	try {
		const current = await fs.promises.readFile(filepath, 'utf8');
		if (current === content) return false;
	} catch {
		// File doesn't exist yet
	}
	await fs.promises.writeFile(filepath, content, 'utf8');
	return true;
}

async function main() {
	fs.mkdirSync(GENERATED_DIR, { recursive: true });

	if (!fs.existsSync(INPUT_DIR)) {
		process.stdout.write(`No input directory found: ${INPUT_DIR}\n`);
		return;
	}

	const svgFiles = fs
		.readdirSync(INPUT_DIR)
		.filter((f) => f.endsWith('.svg'))
		.toSorted();

	if (svgFiles.length === 0) {
		process.stdout.write(`No SVG files found in: ${INPUT_DIR}\n`);
		return;
	}

	const iconNames: Array<string> = [];
	const seenIconNames = new Set<string>();
	// Standalone SVG source per icon, `currentColor` forced to an opaque colour so
	// it survives as a CSS mask image: `mask-image` masks by alpha channel, not by
	// the resolved colour, but `currentColor` in a detached data-URI document has
	// no ancestor to inherit from, so it must be replaced with a literal colour to
	// render as opaque at all.
	const maskSources: Record<string, string> = {};

	for (const file of svgFiles) {
		const iconName = path.basename(file, '.svg');
		const filePath = path.join(INPUT_DIR, file);

		try {
			const svgContent = fs.readFileSync(filePath, 'utf8');
			const root = parse(svgContent);
			const svg = root.querySelector('svg');

			if (!svg) {
				process.stdout.write(`Skipping "${file}": no <svg> element found\n`);
				continue;
			}

			if (seenIconNames.has(iconName)) {
				process.stdout.write(`Skipping "${file}": duplicate icon id "${iconName}"\n`);
				continue;
			}

			seenIconNames.add(iconName);
			iconNames.push(iconName);
			maskSources[iconName] = svgContent.replaceAll('currentColor', 'black');
		} catch (err) {
			const message = err instanceof Error ? err.message : String(err);
			process.stdout.write(`Failed to read "${file}": ${message}\n`);
		}
	}

	if (iconNames.length === 0) {
		process.stdout.write('No valid SVGs found after parsing\n');
		return;
	}

	const iconDataTs = `/* This file is generated by scripts/build-icons.ts */

export const iconNames = [${iconNames.map((n) => `'${n}'`).join(', ')}] as const;

export type IconName = (typeof iconNames)[number];
`;

	// Kept separate from `icon-data.ts`, which runtime code imports for the icon names. This module
	// is only imported by build-time `.css.ts` files, so the SVG sources reach the shipped CSS and
	// never the client bundle.
	const iconMaskDataTs = `/* This file is generated by scripts/build-icons.ts */

import type { IconName } from './icon-data.js';

export const iconMaskUrls: Record<IconName, string> = {
${iconNames.map((n) => `\t'${n}': ${JSON.stringify(`url("data:image/svg+xml,${toDataUriPayload(maskSources[n] ?? '')}")`)}`).join(',\n')}
} as const;
`;

	const [iconDataChanged, iconMaskDataChanged] = await Promise.all([
		writeIfChanged(ICON_DATA_TS_PATH, iconDataTs),
		writeIfChanged(ICON_MASK_DATA_TS_PATH, iconMaskDataTs),
	]);

	if (iconDataChanged || iconMaskDataChanged) {
		process.stdout.write(`Generated icon data for ${iconNames.length} icons\n`);
	} else {
		process.stdout.write(`Icon data up to date (${iconNames.length} icons)\n`);
	}
}

main().catch((err) => {
	const message = err instanceof Error ? (err.stack ?? err.message) : String(err);
	process.stderr.write(`Failed to build icons: ${message}\n`);
	process.exit(1);
});
